"""Generates crates/ibex-sample/src/argspec_table.rs from the HAProxy source (T343).

Every sample fetch and converter keyword list in HAProxy's src/*.c declares, per keyword, an
argument mask (ARGn(min, T1, ...), include/haproxy/arg.h), a val_args function, and its types
(a fetch: output type; a converter: input and output types). Every ACL keyword list names
the fetch an ACL keyword stands for. This reads them all, so that Ibex checks each argument
against the type HAProxy declares for it, rather than against a hand-copied table.

    python3 tools/gen_sample_argspecs.py /home/bhenc/reference/haproxy > crates/ibex-sample/src/argspec_table.rs
"""
import glob
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/home/bhenc/reference/haproxy"
KW = re.compile(
    r'\{\s*"([^"]+)"\s*,\s*([A-Za-z_0-9]+)\s*,\s*(0|ARG\d+\([^)]*\))\s*,\s*([A-Za-z_0-9]+)\s*,'
    r'\s*(SMP_T_[A-Z0-9]+)\s*,\s*([A-Z0-9_|\s]+?)\s*[,}]'
)
ACL = re.compile(r'\{\s*"([^"]+)"\s*,\s*("([^"]*)"|NULL)\s*,\s*PAT_MATCH_')
ARGT = {
    "SINT": "Sint", "STR": "Str", "ID": "Id", "IPV4": "Ipv4", "MSK4": "Msk4", "IPV6": "Ipv6",
    "MSK6": "Msk6", "TIME": "Time", "SIZE": "Size", "FE": "Fe", "BE": "Be", "TAB": "Tab",
    "SRV": "Srv", "USR": "Usr", "MAP": "Map", "REG": "Reg", "VAR": "Var", "PBUF_FNUM": "PbufFnum",
}
SMPT = {
    "ANY": "Any", "SAME": "Same", "BOOL": "Bool", "SINT": "Sint", "ADDR": "Addr", "IPV4": "Ipv4",
    "IPV6": "Ipv6", "STR": "Str", "BIN": "Bin", "METH": "Meth",
}


def mask(m):
    if m == "0":
        return 0, []
    inner = m[m.index("(") + 1:-1].split(",")
    return int(inner[0]), [ARGT[t.strip()] for t in inner[1:]]


def rust_kw(name, m, val, in_t, out_t, origin):
    lo, types = mask(m)
    v = "None" if val == "NULL" else 'Some("%s")' % val
    args = ", ".join("A::" + t for t in types)
    return '    KwSpec { name: "%s", min: %d, args: &[%s], val: %s, in_type: T::%s, out_type: T::%s }, // %s' % (
        name, lo, args, v, in_t, out_t, origin)


fetches, convs, acls = {}, {}, {}
for path in sorted(glob.glob(SRC + "/src/*.c")):
    text = open(path, errors="replace").read()
    origin = path.rsplit("/", 1)[-1]
    for k in KW.finditer(text):
        name, _fn, m, val, a, b = k.groups()
        b = b.strip()
        if b.startswith("SMP_T_"):
            convs.setdefault(name, (m, val, SMPT[a[6:]], SMPT[b[6:]], origin))
        else:
            fetches.setdefault(name, (m, val, "Any", SMPT[a[6:]], origin))
    for a in ACL.finditer(text):
        acls.setdefault(a.group(1), (a.group(3) or a.group(1), origin))

out = [
    "// SPDX-License-Identifier: GPL-2.0-or-later",
    "// Copyright (C) 2000-2026 Willy Tarreau and HAProxy contributors. See LICENSE.",
    "",
    "//! Generated by `tools/gen_sample_argspecs.py` from the `HAProxy` 3.5-dev8 source: the argument",
    "//! mask, `val_args` function and types of every sample fetch and converter keyword, and the",
    "//! fetch of every ACL keyword. Do not edit; regenerate.",
    "",
    "use super::{ArgType as A, KwSpec, SmpType as T};",
    "",
    "/// The sample fetch keywords, sorted by name.",
    "pub(super) static FETCHES: &[KwSpec] = &[",
]
out += [rust_kw(n, *fetches[n]) for n in sorted(fetches)]
out += ["];", "", "/// The converter keywords, sorted by name.", "pub(super) static CONVERTERS: &[KwSpec] = &["]
out += [rust_kw(n, *convs[n]) for n in sorted(convs)]
out += ["];", "", "/// The ACL keywords and the fetch each stands for, sorted by keyword.",
        "pub(super) static ACL_KEYWORDS: &[(&str, &str)] = &["]
out += ['    ("%s", "%s"), // %s' % (n, acls[n][0], acls[n][1]) for n in sorted(acls)]
out += ["];", ""]
print("\n".join(out))
