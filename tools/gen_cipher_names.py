"""Generate crates/alcyon-tls/src/cipher_names.rs from the host OpenSSL.

Usage: python3 -I tools/gen_cipher_names.py [--stdout]

The table maps a TLS cipher-suite id to the name OpenSSL's SSL_CIPHER_get_name returns,
which is what HAProxy prints for ssl_fc_cipherlist_str.
"""
import os
import re
import subprocess
import sys

# The five TLS 1.3 suites OpenSSL knows; `-tls1_3` alone lists only the three it enables by default,
# and HAProxy's SSL_CIPHER_find names the other two as well (measured: 0x1305 in ssl_capture).
TLS13 = "TLS_AES_256_GCM_SHA384:TLS_CHACHA20_POLY1305_SHA256:TLS_AES_128_GCM_SHA256:TLS_AES_128_CCM_SHA256:TLS_AES_128_CCM_8_SHA256"

LINE = re.compile(r"^\s*0x([0-9A-Fa-f]{2}),0x([0-9A-Fa-f]{2}) - (\S+) ")


def run(*args):
    try:
        return subprocess.run(["openssl", *args], check=True, capture_output=True, text=True).stdout
    except FileNotFoundError:
        sys.exit("openssl-missing: openssl is not installed")


def main():
    version = run("version").strip()
    table = {}
    for out in (run("ciphers", "-V", "ALL:COMPLEMENTOFALL"), run("ciphers", "-V", "-tls1_3", "-ciphersuites", TLS13)):
        for line in out.splitlines():
            m = LINE.match(line)
            if not m:
                continue
            cid = int(m.group(1) + m.group(2), 16)
            if table.setdefault(cid, m.group(3)) != m.group(3):
                sys.exit("conflicting names for 0x%04x" % cid)
    rows = "".join('    (0x%04x, "%s"),\n' % (k, table[k]) for k in sorted(table))
    text = f"""// SPDX-License-Identifier: GPL-2.0-or-later
// Copyright (C) 2000-2026 Willy Tarreau and HAProxy contributors. See LICENSE.

//! Cipher-suite id to OpenSSL name, as `SSL_CIPHER_get_name` returns it.
//!
//! GENERATED by `tools/gen_cipher_names.py` (do not edit) from
//! `openssl ciphers -V 'ALL:COMPLEMENTOFALL'` plus `openssl ciphers -V -tls1_3 -ciphersuites <all five TLS 1.3 suites>`.
//! Generated with: {version}
//! Ids absent here (GREASE, SCSVs, suites this OpenSSL does not compile in) are the caller's
//! `UNKNOWN(%04x)` case.

/// Sorted by id.
const NAMES: [(u16, &str); {len(table)}] = [
{rows}];

/// The OpenSSL name of the suite `id`, or `None` when OpenSSL does not know it.
#[must_use]
pub fn openssl_cipher_name_by_id(id: u16) -> Option<&'static str> {{
    NAMES.binary_search_by_key(&id, |&(k, _)| k).ok().map(|i| NAMES[i].1)
}}

"""
    # keep the hand-written tests at the end of the file
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "..", "crates", "alcyon-tls", "src", "cipher_names.rs")
    with open(path) as f:
        cur = f.read()
    i = cur.find("#[cfg(test)]")
    if i < 0:
        sys.exit("no test module in " + path)
    text += cur[i:]
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        with open(path, "w") as f:
            f.write(text)


main()
