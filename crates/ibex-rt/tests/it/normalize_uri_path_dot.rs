fn ask(addr: SocketAddr, path: &str) -> String {
    let mut s = TcpStream::connect(addr).expect("connect");
    s.set_read_timeout(Some(Duration::from_secs(2))).expect("timeout");
    s.write_all(format!("GET {path} HTTP/1.1\r\nHost: a\r\nConnection: close\r\n\r\n").as_bytes()).expect("send");
    let mut d = Vec::new();
    let _ = s.read_to_end(&mut d);
    let d = String::from_utf8_lossy(&d).into_owned();
    let body = d.split_once("\r\n\r\n").map_or("", |(_, b)| b);
    body.strip_prefix('[').and_then(|b| b.strip_suffix(']')).map_or_else(|| format!("raw:{d}"), str::to_string)
}

#[test]
fn the_path_normalizers_match_haproxy_on_every_measured_path() {
    let addrs = [common::reserve_addr(), common::reserve_addr(), common::reserve_addr()];
    let mut cfg = String::from(
        "global\n  expose-experimental-directives\ndefaults\n  mode http\n  timeout client 5s\n  timeout server 5s\n  timeout connect 1s\n",
    );
    for (i, (addr, norm)) in addrs.iter().zip(["path-strip-dot", "path-strip-dotdot", "path-strip-dotdot full"]).enumerate() {
        let _ = writeln!(
            cfg,
            "frontend f{i}\n  bind {addr}\n  http-request normalize-uri {norm}\n  http-request return status 200 content-type text/plain lf-string \"[%[pathq]]\""
        );
    }
    let path = std::env::temp_dir().join(format!("ibex-t359g-hidden-{}.cfg", std::process::id()));
    std::fs::write(&path, cfg).expect("write cfg");
    let mut ibex = common::Ibex(
        Command::new(env!("CARGO_BIN_EXE_ibex")).arg("-db").arg("-f").arg(&path).stdout(Stdio::null()).stderr(Stdio::null()).spawn().expect("spawn ibex"),
    );
    assert!(addrs.iter().all(|a| common::wait_listening(*a)), "ibex did not listen");
    let mut bad = Vec::new();
    for &(req, dot, dotdot, full) in ROWS {
        for (k, want) in [dot, dotdot, full].into_iter().enumerate() {
            let got = ask(addrs[k], req);
            if got != want {
                bad.push(format!("{} {req:?}: HAProxy {want:?}, Ibex {got:?}", ["path-strip-dot", "path-strip-dotdot", "path-strip-dotdot full"][k]));
            }
        }
    }
    common::stop(&mut ibex);
    let _ = std::fs::remove_file(&path);
    assert!(bad.is_empty(), "{} of {} answers differ from HAProxy, first: {:#?}", bad.len(), ROWS.len() * 3, &bad[..bad.len().min(12)]);
}
