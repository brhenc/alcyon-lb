#[test]
fn field_and_word_match_haproxy_on_every_row() {
    let reg = Registry::new();
    let mut bad = Vec::new();
    for (name, input, args, want) in ROWS {
        let conv = reg.get_converter(name).expect(name);
        let a: Vec<String> = args.iter().map(|s| (*s).to_string()).collect();
        let got = match (conv.func)(Sample::Str((*input).into()), &a) {
            Some(Sample::Str(s)) => Some(s),
            None => None,
            Some(other) => Some(format!("{other:?}")),
        };
        if got.as_deref() != *want {
            bad.push(format!("{name}({}) of {input:?}: HAProxy {want:?}, Ibex {got:?}", args.join(",")));
        }
    }
    assert!(bad.is_empty(), "{} of {} rows differ from HAProxy; the first ones:\n{}", bad.len(), ROWS.len(), bad.iter().take(12).cloned().collect::<Vec<_>>().join("\n"));
}
