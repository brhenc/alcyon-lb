fn unhex(h: &str) -> Vec<u8> {
    (0..h.len() / 2).map(|i| u8::from_str_radix(h.get(i * 2..i * 2 + 2).unwrap_or("00"), 16).unwrap_or(0)).collect()
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn check(conv: &str, rows: &[(&str, &str)]) {
    let reg = Registry::new();
    let c = reg.get_converter(conv).expect(conv);
    let mut bad = Vec::new();
    for (input, want) in rows {
        let got = match (c.func)(Sample::Str(bytes_to_text(&unhex(input))), &[]) {
            Some(Sample::Str(s)) => Some(hex(&text_to_bytes(&s))),
            None => None,
            Some(other) => Some(format!("{other:?}")),
        };
        if got.as_deref() != Some(*want) {
            bad.push(format!("{conv} of bytes {input}: HAProxy {want}, Ibex {got:?}"));
        }
    }
    assert!(bad.is_empty(), "{} of {} rows differ from HAProxy; the first ones:\n{}", bad.len(), rows.len(), bad.iter().take(12).cloned().collect::<Vec<_>>().join("\n"));
}

#[test]
fn upper_changes_ascii_letters_only() {
    check("upper", UPPER);
}

#[test]
fn lower_changes_ascii_letters_only() {
    check("lower", LOWER);
}
