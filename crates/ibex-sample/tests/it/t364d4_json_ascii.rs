/// `json(utf8s)` is not changed by this task: (input hex, HAProxy's answer), all of which Ibex already gives.
const UTF8S_ROWS: &[(&str, &str)] = &[("", ""), ("616263", "abc"), ("80", ""), ("ff", ""), ("61e962", "ab"), ("7f", "\\u007f"), ("011f207e", "\\u0001\\u001f ~")];

fn unhex(h: &str) -> Vec<u8> {
    (0..h.len() / 2).map(|i| u8::from_str_radix(h.get(i * 2..i * 2 + 2).unwrap_or("00"), 16).unwrap_or(0)).collect()
}

fn json(input_hex: &str, args: &[&str]) -> Option<String> {
    let reg = Registry::new();
    let conv = reg.get_converter("json").expect("json");
    let a: Vec<String> = args.iter().map(|s| (*s).to_string()).collect();
    match (conv.func)(Sample::Str(bytes_to_text(&unhex(input_hex))), &a) {
        Some(Sample::Str(s)) => Some(s),
        None => None,
        Some(other) => Some(format!("{other:?}")),
    }
}

#[test]
fn json_ascii_mode_escapes_every_byte_as_haproxy() {
    for args in [&[][..], &[""][..], &["ascii"][..]] {
        let mut bad = Vec::new();
        for (input, want) in ROWS {
            let got = json(input, args);
            if got.as_deref() != Some(*want) {
                bad.push(format!("json({}) of bytes {input}: HAProxy {want:?}, Ibex {got:?}", args.join(",")));
            }
        }
        assert!(bad.is_empty(), "{} of {} rows differ from HAProxy; the first ones:\n{}", bad.len(), ROWS.len(), bad.iter().take(12).cloned().collect::<Vec<_>>().join("\n"));
    }
}

#[test]
fn json_utf8s_mode_is_unchanged() {
    for (input, want) in UTF8S_ROWS {
        assert_eq!(json(input, &["utf8s"]).as_deref(), Some(*want), "json(utf8s) of bytes {input}");
    }
}
