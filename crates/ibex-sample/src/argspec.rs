    /// The converters whose input or output type Ibex declares otherwise than `HAProxy`.
    #[test]
    fn declared_converter_types_against_haproxys() {
        use crate::{SampleType as S, TypeSpec as TS};
        let of = |t: TS| match t {
            TS::Any => SmpType::Any,
            TS::Same => SmpType::Same,
            TS::Addr => SmpType::Addr,
            TS::Exact(S::Bool) => SmpType::Bool,
            TS::Exact(S::Sint) => SmpType::Sint,
            TS::Exact(S::Ipv4) => SmpType::Ipv4,
            TS::Exact(S::Ipv6) => SmpType::Ipv6,
            TS::Exact(S::Str) => SmpType::Str,
            TS::Exact(S::Bin) => SmpType::Bin,
            TS::Exact(S::Meth) => SmpType::Meth,
        };
        let reg = crate::Registry::new();
        let mut differ = Vec::new();
        for name in reg.converter_names() {
            let Some(h) = converter_spec(name) else { continue };
            let (i, o) = reg
                .get_converter(name)
                .map(|d| (d.in_type, d.out_type))
                .or_else(|| reg.get_ctx_converter(name).map(|d| (d.in_type, d.out_type)))
                .expect("registered");
            if (of(i), of(o)) != (h.in_type, h.out_type) {
                differ.push(format!("{name}: ibex {:?}->{:?}, haproxy {:?}->{:?}", of(i), of(o), h.in_type, h.out_type));
            }
        }
        differ.sort();
        // Left as they are (T343): no load check reads these declarations any more
        // (`check_typed_expr` uses `HAProxy`'s), and changing them changes how the input is cast
        // or how an ACL matches by default, each wanting its own measured test.
        let known = [
            "jwt_header_query: ibex Str->Any, haproxy Bin->Any",
            "jwt_payload_query: ibex Str->Any, haproxy Bin->Any",
            "jwt_verify: ibex Str->Sint, haproxy Bin->Sint",
            "length: ibex Any->Sint, haproxy Str->Sint",
            "mqtt_field_value: ibex Bin->Any, haproxy Bin->Str",
            "protobuf: ibex Bin->Any, haproxy Bin->Bin",
            "rfc7239_n2nn: ibex Str->Str, haproxy Str->Any",
            "rfc7239_n2np: ibex Str->Str, haproxy Str->Any",
            "ungrpc: ibex Bin->Any, haproxy Bin->Bin",
        ];
        assert_eq!(differ, known, "converters whose declared types differ from HAProxy's");
    }

    #[test]
    fn read_int64_takes_a_sign_and_digits_and_saturates() {
        assert_eq!(read_int64_whole("-"), Some(0));
        assert_eq!(read_int64_whole(""), Some(0));
        assert_eq!(read_int64_whole("+5"), Some(5));
        assert_eq!(read_int64_whole("0x10"), None);
        assert_eq!(read_int64_whole(" 1"), None);
        assert_eq!(read_int64_whole("99999999999999999999"), Some(i64::MAX));
        assert_eq!(read_int64_whole("-99999999999999999999"), Some(i64::MIN));
    }

