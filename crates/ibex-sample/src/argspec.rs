/// A sample type as `HAProxy` declares it (`SMP_T_*`), the pseudo types included.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SmpType {
    Any,
    Same,
    Bool,
    Sint,
    Addr,
    Ipv4,
    Ipv6,
    Str,
    Bin,
    Meth,
}

/// One keyword of `HAProxy`'s fetch or converter lists.
#[derive(Debug)]
pub struct KwSpec {
    pub name: &'static str,
    /// How many arguments are mandatory.
    pub min: u8,
    /// The type of each argument, in order: the most it takes.
    pub args: &'static [ArgType],
    /// The `val_args` function, by its C name.
    pub val: Option<&'static str>,
    /// A converter's input type (`Any` for a fetch).
    pub in_type: SmpType,
    pub out_type: SmpType,
}

fn find(list: &'static [KwSpec], name: &str) -> Option<&'static KwSpec> {
    list.binary_search_by(|k| k.name.cmp(name)).ok().map(|i| &list[i])
}

/// `HAProxy`'s declaration of the fetch `name`.
#[must_use]
pub fn fetch_spec(name: &str) -> Option<&'static KwSpec> {
    find(table::FETCHES, name)
}

/// `HAProxy`'s declaration of the converter `name`.
#[must_use]
pub fn converter_spec(name: &str) -> Option<&'static KwSpec> {
    find(table::CONVERTERS, name)
}

/// The fetch the ACL keyword `name` stands for (`hdr` is `req.hdr`), if it is one.
#[must_use]
pub fn acl_keyword_fetch(name: &str) -> Option<&'static str> {
    table::ACL_KEYWORDS.binary_search_by(|(k, _)| (*k).cmp(name)).ok().map(|i| table::ACL_KEYWORDS[i].1)
}

/// What `sample_casts[from][to]` holds: no cast, the identity (`c_none`) or a conversion.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Cast {
    Refused,
    Identity,
    Converts,
}

/// `sample_casts` (`src/sample.c`).
fn cast(from: SmpType, to: SmpType) -> Cast {
    use Cast::{Converts as C, Identity as I, Refused as N};
    use SmpType as T;
    //            to: ANY SAME BOOL SINT ADDR IPV4 IPV6 STR BIN METH
    const M: [[Cast; 10]; 10] = [
        /* ANY  */ [I, N, C, C, C, C, C, C, C, C],
        /* SAME */ [N, N, N, N, N, N, N, N, N, N],
        /* BOOL */ [I, N, I, I, N, N, N, C, C, N],
        /* SINT */ [I, N, I, I, C, C, C, C, C, N],
        /* ADDR */ [I, N, N, N, C, C, C, C, C, N],
        /* IPV4 */ [I, N, N, C, I, I, C, C, C, N],
        /* IPV6 */ [I, N, N, N, I, C, I, C, C, N],
        /* STR  */ [I, N, C, C, C, C, C, I, I, C],
        /* BIN  */ [I, N, N, N, N, N, N, C, I, C],
        /* METH */ [I, N, N, N, N, N, N, C, C, I],
    ];
    let idx = |t: SmpType| match t {
        T::Any => 0,
        T::Same => 1,
        T::Bool => 2,
        T::Sint => 3,
        T::Addr => 4,
        T::Ipv4 => 5,
        T::Ipv6 => 6,
        T::Str => 7,
        T::Bin => 8,
        T::Meth => 9,
    };
    M[idx(from)][idx(to)]
}

/// An argument once `make_arg_list` and the `val_args` functions have parsed it.
#[derive(Clone, Debug, PartialEq)]
pub enum Arg {
    Sint(i64),
    Str(String),
    Ipv4(Ipv4Addr),
    Ipv6(Ipv6Addr),
    Fnum(Vec<u32>),
    Var(String),
}

impl Arg {
    fn str(&self) -> &str {
        match self {
            Arg::Str(s) | Arg::Var(s) => s,
            _ => "",
        }
    }
    fn sint(&self) -> i64 {
        match self {
            Arg::Sint(i) => *i,
            _ => 0,
        }
    }
}

/// `read_int64` (`src/tools.c`): a sign, then digits, saturating; the value and how many bytes
/// it took.
fn read_int64(s: &[u8]) -> (i64, usize) {
    let (neg, mut at) = match s.first() {
        Some(b'-') => (true, 1),
        Some(b'+') => (false, 1),
        _ => (false, 0),
    };
    let mut i: u64 = 0;
    let mut saturated = false;
    while let Some(d) = s.get(at).filter(|c| c.is_ascii_digit()) {
        if !saturated {
            if let Some(n) = i.checked_mul(10).and_then(|t| t.checked_add(u64::from(d - b'0'))) {
                i = n;
            } else {
                i = u64::MAX;
                saturated = true;
            }
        }
        at += 1;
    }
    let v = if neg {
        if i > 0x8000_0000_0000_0000 { i64::MIN } else { 0i64.wrapping_sub_unsigned(i) }
    } else {
        i64::try_from(i).unwrap_or(i64::MAX)
    };
    (v, at)
}

/// An integer `read_int64` takes whole (`check_operator`, `val_payload_lv`): the empty string
/// and a lone sign are 0.
#[must_use]
pub fn read_int64_whole(s: &str) -> Option<i64> {
    let (v, n) = read_int64(s.as_bytes());
    (n == s.len()).then_some(v)
}

/// `strtol(s, &end, 10)` taken whole, leading blanks and a sign allowed (`str2mask`).
fn strtol_whole(s: &str) -> Option<i64> {
    let t = s.trim_start_matches([' ', '\t', '\n', '\r', '\x0b', '\x0c']);
    let digits = t.strip_prefix(['+', '-']).unwrap_or(t);
    if digits.is_empty() || !digits.bytes().all(|c| c.is_ascii_digit()) {
        return None;
    }
    Some(t.parse::<i64>().unwrap_or(if t.starts_with('-') { i64::MIN } else { i64::MAX }))
}

/// `str2mask` / `str2mask6`: a dotted (or colon) mask, or a length up to `max`.
fn mask_len_ok(s: &str, max: i64) -> bool {
    // `(unsigned)len > max`: a negative length is refused too.
    !s.is_empty() && strtol_whole(s).is_some_and(|n| (0..=max).contains(&n))
}

/// `parse_dotted_uints`: numbers separated by single dots, none empty, no trailing dot.
fn parse_dotted_uints(s: &str) -> Option<Vec<u32>> {
    let b = s.as_bytes();
    let mut out = Vec::new();
    let mut at = 0;
    while at < b.len() {
        let mut n: u32 = 0;
        while let Some(d) = b.get(at).filter(|c| c.is_ascii_digit()) {
            n = n.wrapping_mul(10).wrapping_add(u32::from(d - b'0'));
            at += 1;
        }
        if at < b.len() {
            if b[at] != b'.' || at + 1 == b.len() {
                return None;
            }
            at += 1;
        }
        out.push(n);
    }
    Some(out)
}

/// What [`make_arg_list`] made of a keyword's arguments: `None` when it built no argument
/// array (`arg_p` left `NULL`: the keyword takes none, or none was written and none is
/// mandatory), the arguments, and where the text after them starts.
type Parsed = (Option<Vec<Arg>>, usize);

/// `make_arg_list` (`src/arg.c`) on `s[at..]`, the text right after a keyword's name. An error
/// is the argument position `HAProxy` reports (`err_arg`) and its message.
///
/// # Errors
/// The first argument that does not parse as its type, a missing mandatory one, or what follows
/// the last argument the keyword takes.
#[allow(clippy::too_many_lines)]
pub fn make_arg_list(s: &[u8], at: usize, spec: &KwSpec) -> Result<Parsed, (usize, String)> {
    let mut i = at;
    let empty = s.get(i) != Some(&b'(');
    if !empty {
        i += 1;
    }
    let nbarg = spec.args.len();
    let min = usize::from(spec.min);
    let ty = |p: usize| spec.args.get(p).map_or("end of arguments", |t| t.name());
    let mut pos = 0;
    let mut list: Vec<Arg> = Vec::new();
    // Whether an argument array was built (`arg_p` not left `NULL`).
    let mut built = false;
    'parse: {
        if nbarg == 0 || (empty && min == 0) {
            break 'parse;
        }
        built = true;
        while pos < nbarg {
            let (mut sq, mut dq) = (false, false);
            let mut out: Vec<u8> = Vec::new();
            while !empty && i < s.len() {
                let c = s[i];
                if c == b'"' && !sq {
                    dq = !dq;
                    i += 1;
                    continue;
                }
                if c == b'\'' && !dq {
                    sq = !sq;
                    i += 1;
                    continue;
                }
                if c == b'\\' && !sq {
                    let Some(&n) = s.get(i + 1) else {
                        let rest = String::from_utf8_lossy(&s[i..]);
                        let done = String::from_utf8_lossy(&out);
                        return Err((pos, format!("failed to parse '{rest}' after '{done}' as type '{}' at position {}", ty(pos), pos + 1)));
                    };
                    match n {
                        b'\\' | b' ' | b'"' | b'\'' => {
                            out.push(n);
                            i += 1;
                        }
                        b'r' => {
                            out.push(b'\r');
                            i += 1;
                        }
                        b'n' => {
                            out.push(b'\n');
                            i += 1;
                        }
                        b't' => {
                            out.push(b'\t');
                            i += 1;
                        }
                        _ => out.push(b'\\'),
                    }
                    i += 1;
                    continue;
                }
                if !sq && !dq && (c == b',' || c == b')') {
                    break;
                }
                out.push(c);
                i += 1;
            }
            let text = String::from_utf8_lossy(&out).into_owned();
            let t = spec.args[pos];
            let needs_value = matches!(t, ArgType::Sint | ArgType::Ipv4 | ArgType::Msk4 | ArgType::Ipv6 | ArgType::Msk6 | ArgType::Time | ArgType::Size | ArgType::PbufFnum);
            if needs_value && text.is_empty() {
                // empty_err: no argument at all is no argument array.
                if pos == 0 {
                    built = false;
                }
                if pos >= min {
                    break 'parse;
                }
                return Err((pos, format!("expected type '{}' at position {}, but got nothing", ty(pos), pos + 1)));
            }
            let parse_err = || Err((pos, format!("failed to parse '{text}' as type '{}' at position {}", ty(pos), pos + 1)));
            let arg = match t {
                ArgType::Sint => match read_int64_whole(&text) {
                    Some(v) => Arg::Sint(v),
                    None => return parse_err(),
                },
                ArgType::Ipv4 => match text.parse::<Ipv4Addr>() {
                    Ok(a) => Arg::Ipv4(a),
                    Err(_) => return parse_err(),
                },
                ArgType::Msk4 => {
                    let ok = if text.contains('.') { text.parse::<Ipv4Addr>().is_ok() } else { mask_len_ok(&text, 32) };
                    if !ok {
                        return parse_err();
                    }
                    Arg::Str(text)
                }
                ArgType::Ipv6 => match text.parse::<Ipv6Addr>() {
                    Ok(a) => Arg::Ipv6(a),
                    Err(_) => return parse_err(),
                },
                ArgType::Msk6 => {
                    let ok = if text.contains(':') { text.parse::<Ipv6Addr>().is_ok() } else { mask_len_ok(&text, 128) };
                    if !ok {
                        return parse_err();
                    }
                    Arg::Str(text)
                }
                ArgType::PbufFnum => match parse_dotted_uints(&text) {
                    Some(f) => Arg::Fnum(f),
                    None => return parse_err(),
                },
                ArgType::Map | ArgType::Var => {
                    return Err((pos, format!("parsing for type '{}' was not implemented, please report this bug", ty(pos))));
                }
                // No keyword of 3.5-dev8 declares a delay or a size; kept as written.
                ArgType::Time | ArgType::Size | ArgType::Str | ArgType::Id | ArgType::Fe | ArgType::Be | ArgType::Tab | ArgType::Srv | ArgType::Usr | ArgType::Reg => Arg::Str(text),
            };
            list.push(arg);
            pos += 1;
            if empty || i >= s.len() || s[i] == b')' || pos >= nbarg {
                break;
            }
            i += 1;
        }
    }
    if pos < min {
        return Err((pos, format!("missing arguments (got {pos}/{min}), type '{}' expected", ty(pos))));
    }
    if !empty {
        if s.get(i) == Some(&b')') {
            i += 1;
        } else {
            let word = String::from_utf8_lossy(&s[i.min(s.len())..]);
            let msg = if word.is_empty() { "expected ')'".to_string() } else { format!("expected ')' before '{word}'") };
            return Err((if pos > 1 { pos - 1 } else { pos }, msg));
        }
    }
    Ok((built.then_some(list), i))
}

/// `HTTP_IS_TOKEN`: a `tchar` of RFC 9110.
fn is_tchar(c: u8) -> bool {
    c.is_ascii_alphanumeric() || b"!#$%&'*+-.^_`|~".contains(&c)
}

/// `strtoul(s, &end, 0)` taken whole: decimal, `0x` hexadecimal or `0` octal, after blanks and
/// a sign. `None` when text is left over.
fn strtoul0_whole(s: &str) -> Option<u64> {
    let t = s.trim_start_matches([' ', '\t', '\n', '\r', '\x0b', '\x0c']);
    let (neg, t) = match t.as_bytes().first() {
        Some(b'-') => (true, &t[1..]),
        Some(b'+') => (false, &t[1..]),
        _ => (false, t),
    };
    let (radix, digits) = if let Some(h) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
        (16, h)
    } else if t.len() > 1 && t.starts_with('0') {
        (8, &t[1..])
    } else {
        (10, t)
    };
    if digits.is_empty() && radix != 8 {
        return None;
    }
    let v = if digits.is_empty() { 0 } else { u64::from_str_radix(digits, radix).ok()? };
    Some(if neg { v.wrapping_neg() } else { v })
}

/// `is_idchar` (`include/haproxy/tools.h`).
fn is_idchar(c: u8) -> bool {
    c.is_ascii_alphanumeric() || matches!(c, b'.' | b'_' | b'-' | b'+' | b':')
}

fn idchars(s: &[u8], at: usize) -> usize {
    at + s[at..].iter().take_while(|&&c| is_idchar(c)).count()
}

/// `vars_check_arg` (`src/vars.c`) on a variable name. `HAProxy` reports a bad scope as
/// "(null)": `vars_fill_desc` writes its message only when it was given none to write to.
fn vars_check(name: &str) -> Result<(), String> {
    if name.is_empty() {
        return Err("Empty variable name cannot be accepted".to_string());
    }
    let (scope, rest) = name.split_once('.').map_or((name, None), |(s, r)| (s, Some(r)));
    let rest = if matches!(scope, "proc" | "sess" | "txn" | "req" | "res" | "check") {
        rest.filter(|r| !r.is_empty())
    } else {
        ["psess.", "ptxn.", "preq.", "pres."].iter().find_map(|p| name.strip_prefix(p)).filter(|r| !r.is_empty())
    };
    let Some(rest) = rest else { return Err("(null)".to_string()) };
    match rest.bytes().find(|c| !c.is_ascii_alphanumeric() && !matches!(c, b'_' | b'.')) {
        Some(c) => Err(format!("Invalid character '{}' in variable name {rest}", char::from(c))),
        None => Ok(()),
    }
}

/// Whether `name` is a variable `vars_check_arg` accepts.
#[must_use]
pub fn is_variable(name: &str) -> bool {
    vars_check(name).is_ok()
}

/// `check_operator`: a variable, else an integer `read_int64` takes whole.
fn check_operator(arg: &mut Arg) -> Result<(), String> {
    let s = arg.str().to_string();
    if vars_check(&s).is_ok() {
        *arg = Arg::Var(s);
        return Ok(());
    }
    match read_int64_whole(&s) {
        Some(v) => {
            *arg = Arg::Sint(v);
            Ok(())
        }
        None => Err("expects an integer or a variable name".to_string()),
    }
}

/// The date units of `smp_check_date_unit`.
fn date_unit(arg: Option<&Arg>) -> Result<(), String> {
    match arg {
        Some(Arg::Str(u)) if !matches!(u.as_str(), "s" | "ms" | "us") => Err(format!("expects 's', 'ms' or 'us', got '{u}'")),
        _ => Ok(()),
    }
}

/// The names `smp_check_tlv_type` takes for a PROXY protocol TLV type.
const TLV_NAMES: &[&str] = &[
    "ALPN", "AUTHORITY", "CRC32C", "NOOP", "UNIQUE_ID", "SSL", "SSL_VERSION", "SSL_CN", "SSL_CIPHER",
    "SSL_SIG_ALG", "SSL_KEY_ALG", "NETNS",
];

/// `when_cond_kw[]`, in `HAProxy`'s order.
const WHEN_KEYWORDS: &[&str] = &["stopping", "normal", "error", "forwarded", "toapplet", "processed", "acl"];

/// A fetch's `val_args`, by `HAProxy`'s function name. Functions not ported accept.
#[allow(clippy::too_many_lines)]
fn val_fetch(val: &str, args: &mut [Arg]) -> Result<(), String> {
    match val {
        "val_hdr" => match args.get(1) {
            Some(Arg::Sint(n)) if *n < -10 => Err("header occurrence must be >= -10".to_string()),
            _ => Ok(()),
        },
        "smp_check_date_unit" => date_unit(args.get(1)),
        "smp_check_accept_date_unit" => date_unit(args.first()),
        "val_payload_lv" => {
            if args.first().map_or(0, Arg::sint) < 0 {
                return Err("payload offset1 must be positive".to_string());
            }
            if args.get(1).map_or(0, Arg::sint) == 0 {
                return Err("payload length must be > 0".to_string());
            }
            match args.get(2) {
                Some(Arg::Str(s)) if !s.is_empty() => match read_int64_whole(s) {
                    None => Err("payload offset2 is not a number".to_string()),
                    Some(o) if args[0].sint().saturating_add(args[1].sint()).saturating_add(o) < 0 => {
                        Err("payload offset2 too negative".to_string())
                    }
                    Some(_) => Ok(()),
                },
                _ => Ok(()),
            }
        }
        "smp_check_const_bin" => {
            let s = args.first().map_or("", Arg::str).as_bytes();
            if !s.len().is_multiple_of(2) {
                return Err("an even number of hex digit is expected".to_string());
            }
            // `parse_binary` reports the second digit of the pair when the first is bad too.
            for pair in s.chunks(2) {
                if !pair[0].is_ascii_hexdigit() {
                    return Err(format!("an hex digit is expected (found '{}')", char::from(pair[0])));
                }
                if !pair[1].is_ascii_hexdigit() {
                    return Err(format!("an hex digit is expected (found '{}')", char::from(pair[1])));
                }
            }
            Ok(())
        }
        "smp_check_const_bool" => {
            let s = args.first().map_or("", Arg::str).to_ascii_lowercase();
            if matches!(s.as_str(), "true" | "1" | "false" | "0") {
                Ok(())
            } else {
                Err("Expects 'true', 'false', '0' or '1'".to_string())
            }
        }
        "smp_check_const_meth" => {
            let s = args.first().map_or("", Arg::str);
            if s.bytes().all(is_tchar) {
                Ok(())
            } else {
                Err("expects valid method.".to_string())
            }
        }
        "smp_check_uuid" => match args.first() {
            Some(Arg::Sint(v)) if !matches!(v, 4 | 7) => Err(format!("Unsupported UUID version: '{v}'")),
            _ => Ok(()),
        },
        "smp_check_var" => vars_check(args.first().map_or("", Arg::str)),
        "smp_check_tlv_type" => {
            let s = args.first().map_or("", Arg::str);
            if TLV_NAMES.iter().any(|n| n.eq_ignore_ascii_case(s)) {
                return Ok(());
            }
            match strtoul0_whole(s) {
                None => Err(format!("Could not convert type '{s}'")),
                Some(t) if t > 255 => Err(format!("Invalid TLV Type '{s}'")),
                Some(_) => Ok(()),
            }
        }
        "val_distcc" => {
            if args.first().map_or(0, |a| a.str().len()) == 4 {
                Ok(())
            } else {
                Err("token name must be exactly 4 characters".to_string())
            }
        }
        "val_fc_time_value" => match args.first() {
            Some(Arg::Str(u)) if u == "us" || u == "ms" => Ok(()),
            Some(Arg::Str(u)) => Err(format!("expects 'us' or 'ms', got '{u}'")),
            _ => Err("Unexpected arg type".to_string()),
        },
        "val_cap_id" => match args.first() {
            Some(Arg::Sint(n)) if *n < 0 => Err("capture identifier must be >= 0".to_string()),
            _ => Ok(()),
        },
        "val_query" => match args.first() {
            Some(Arg::Str(s)) if !s.is_empty() && s != "with_qm" => Err("supported options are: 'with_qm'".to_string()),
            _ => Ok(()),
        },
        "val_blk_arg" => {
            let s = args.first().map_or("", Arg::str);
            if s.is_empty() {
                Err("a block position is expected (> 0) or a special block name (head, tail, first)".to_string())
            } else if matches!(s, "head" | "tail" | "first") || s.bytes().all(|c| c.is_ascii_digit()) {
                Ok(())
            } else {
                Err("invalid block position".to_string())
            }
        }
        _ => Ok(()),
    }
}

/// How a converter's `val_args` failed: its message, which `sample_parse_expr_cnv` prefixes
/// ("invalid args in converter '%s' : "), or a whole message from a check written before this
/// one ([`crate::registry::check_converter_args`]).
enum ValErr {
    Inner(String),
    Whole(String),
}

/// A converter's `val_args`, by `HAProxy`'s function name. The ones Ibex checked already
/// (`check_converter_args`, T330/T341) are called from there.
#[allow(clippy::too_many_lines)]
fn val_conv(name: &str, val: &str, args: &mut [Arg]) -> Result<(), ValErr> {
    let inner = |m: String| Err(ValErr::Inner(m));
    match val {
        "check_operator" => args.first_mut().map_or(Ok(()), check_operator).map_err(ValErr::Inner),
        "sample_conv_bytes_check" => {
            if let Some(a) = args.get_mut(0) {
                check_operator(a).map_err(ValErr::Inner)?;
                if matches!(a, Arg::Sint(n) if *n < 0) {
                    return inner("expects a non-negative integer".to_string());
                }
            }
            if let Some(a) = args.get_mut(1) {
                check_operator(a).map_err(ValErr::Inner)?;
                if matches!(a, Arg::Sint(n) if *n <= 0) {
                    return inner("expects a positive integer".to_string());
                }
            }
            Ok(())
        }
        "sample_conv_field_check" => {
            if args.first().map_or(0, Arg::sint) == 0 {
                return inner("Unexpected value 0 for index".to_string());
            }
            if args.get(1).map_or("", Arg::str).is_empty() {
                return inner("Empty separators list".to_string());
            }
            Ok(())
        }
        "sample_conv_json_check" => match args.first().map_or("", Arg::str) {
            "" | "ascii" | "utf8" | "utf8s" | "utf8p" | "utf8ps" => Ok(()),
            _ => inner("Unexpected input code type. Allowed value are 'ascii', 'utf8', 'utf8s', 'utf8p' and 'utf8ps'".to_string()),
        },
        "sample_conv_regsub_check" => match args.get(2).map_or("", Arg::str).bytes().find(|c| !matches!(c, b'i' | b'g')) {
            Some(c) => inner(format!("invalid regex flag '{}', only 'i' and 'g' are supported", char::from(c))),
            None => Ok(()),
        },
        "smp_check_concat" => {
            let v = args.get(1).map_or("", Arg::str);
            if !v.is_empty() && vars_check(v).is_err() {
                return inner(format!("failed to register variable name '{v}'"));
            }
            Ok(())
        }
        "smp_check_add_item" => {
            let v = args.get(1).map_or("", Arg::str);
            if !v.is_empty() && vars_check(v).is_err() {
                return inner(format!("failed to register variable name '{v}'"));
            }
            if v.is_empty() && args.get(2).map_or("", Arg::str).is_empty() {
                return inner("one of the optional arguments has to be nonempty".to_string());
            }
            Ok(())
        }
        "smp_check_sha2" => match args.first() {
            Some(Arg::Sint(b)) if !matches!(b, 224 | 256 | 384 | 512) => inner(format!("Unsupported number of bits: '{b}'")),
            _ => Ok(()),
        },
        "sample_conv_2dec_check" => {
            let size = args.get(1).map_or(0, Arg::sint);
            if size <= 0 || size > 8 {
                return inner(format!("chunk_size out of [1..8] range ({size})"));
            }
            let t = args.get(2).map_or(0, Arg::sint);
            if t != 0 && t != 1 {
                return inner(format!("Unsupported truncate value ({t})"));
            }
            Ok(())
        }
        "sample_conv_be2hex_check" => {
            let size = args.get(1).map_or(0, Arg::sint);
            let t = args.get(2).map_or(0, Arg::sint);
            if size <= 0 && (!args.first().map_or("", Arg::str).is_empty() || t != 0) {
                return inner(format!("chunk_size needs to be positive ({size})"));
            }
            if t != 0 && t != 1 {
                return inner(format!("Unsupported truncate value ({t})"));
            }
            Ok(())
        }
        "smp_check_http_date_unit" => date_unit(args.get(1)).map_err(ValErr::Inner),
        "check_crypto_digest" => {
            let alg = args.first().map_or("", Arg::str);
            if crate::registry::digest_by_name(alg).is_some() {
                Ok(())
            } else if crate::registry::digest_unimplemented(alg) {
                Err(ValErr::Whole(format!("converter 'digest' with digest '{alg}' is not implemented by Ibex")))
            } else {
                inner("algorithm must be a valid OpenSSL message digest name.".to_string())
            }
        }
        "conv_check_var" => vars_check(args.first().map_or("", Arg::str)).map_err(ValErr::Inner),
        "check_when_cond" => {
            let kw = args.first().map_or("", Arg::str);
            let kw = kw.strip_prefix('!').unwrap_or(kw);
            if !WHEN_KEYWORDS.contains(&kw) {
                return inner(format!("expects a supported keyword among {{{}}} but got '{kw}'", WHEN_KEYWORDS.join(",")));
            }
            if kw == "acl" && args.get(1).map_or("", Arg::str).is_empty() {
                return inner("'acl' selector requires an extra argument with the ACL name".to_string());
            }
            Ok(())
        }
        "sample_conv_fix_value_check" => {
            let t = args.first().map_or("", Arg::str);
            if crate::fix::tag_id(t).is_some_and(|id| id != 0) {
                Ok(())
            } else {
                inner(format!("Unknown FIX tag name '{t}'"))
            }
        }
        _ => {
            // The checks written before this one take the arguments as text.
            let text: Vec<String> = args.iter().map(arg_text).collect();
            match crate::registry::check_converter_args(name, &text) {
                Some(m) => Err(ValErr::Whole(m)),
                None => Ok(()),
            }
        }
    }
}

/// An argument as it was written, for the checks that read text.
fn arg_text(a: &Arg) -> String {
    match a {
        Arg::Sint(i) => i.to_string(),
        Arg::Str(s) | Arg::Var(s) => s.clone(),
        Arg::Ipv4(a) => a.to_string(),
        Arg::Ipv6(a) => a.to_string(),
        Arg::Fnum(f) => f.iter().map(u32::to_string).collect::<Vec<_>>().join("."),
    }
}

/// Checks the sample expression `expr` -- the fetch, its arguments and its converters, with no
/// ACL pattern or log-format text around it -- as `sample_parse_expr` does at load: each
/// argument against its declared type, the `val_args` functions, and each converter's input
/// type against what precedes it. `acl` is an ACL's expression (`parse_acl_expr`): an ACL
/// keyword (`hdr`, `path_beg`) says "ACL keyword '%s'", and any other failure ends in " in ACL
/// expression '%s'".
///
/// A fetch or converter `HAProxy` does not have ends the check there: the caller's name checks
/// refuse it, or it is one Ibex adds.
///
/// # Errors
/// The first failure, in `HAProxy`'s words, without the context's prefix.
pub fn check_typed_expr(expr: &str, acl: bool) -> Result<(), String> {
    let s = expr.as_bytes();
    let fend = idchars(s, 0);
    let fname = &expr[..fend];
    let aclkw = if acl { acl_keyword_fetch(fname) } else { None };
    let Some(spec) = fetch_spec(aclkw.unwrap_or(fname)) else { return Ok(()) };
    let in_acl = |m: String| if acl && aclkw.is_none() { format!("{m} in ACL expression '{expr}'") } else { m };
    let (args, end) = make_arg_list(s, fend, spec).map_err(|(_, m)| match aclkw {
        Some(_) => format!("ACL keyword '{fname}' : {m}"),
        None => in_acl(format!("fetch method '{fname}' : {m}")),
    })?;
    if let (Some(mut args), Some(val)) = (args, spec.val) {
        val_fetch(val, &mut args).map_err(|m| match aclkw {
            Some(_) => format!("in argument to '{fname}', {m}"),
            None => in_acl(format!("invalid args in fetch method '{fname}' : {m}")),
        })?;
    }
    let conv_err = |m: String| match aclkw {
        Some(_) => format!("ACL keyword '{fname}' : {m}"),
        None => in_acl(m),
    };
    let mut regexes: Vec<(String, usize, &str)> = Vec::new();
    let mut prev = spec.out_type;
    let mut i = end;
    let mut ckw: Option<&str> = None;
    loop {
        if i < s.len() && s[i] != b',' {
            return Err(conv_err(match ckw {
                Some(c) => format!("missing comma after converter '{c}'"),
                None => "missing comma after fetch keyword".to_string(),
            }));
        }
        while s.get(i) == Some(&b',') {
            i += 1;
        }
        if i >= s.len() {
            break;
        }
        let cend = idchars(s, i);
        let cname = &expr[i..cend];
        let Some(conv) = converter_spec(cname) else { return Ok(()) };
        ckw = Some(cname);
        let how = cast(prev, conv.in_type);
        if how == Cast::Refused {
            return Err(conv_err(format!("converter '{cname}' cannot be applied")));
        }
        if conv.out_type != SmpType::Same {
            prev = conv.out_type;
        } else if how != Cast::Identity {
            // `sample_casts[prev][in] != c_none`: a converter that keeps its input's type
            // gives what it was cast to; one it takes as it is (`debug` after `bin`) the type
            // before it.
            prev = conv.in_type;
        }
        let (args, next) = make_arg_list(s, cend, conv)
            .map_err(|(p, m)| conv_err(format!("invalid arg {} in converter '{cname}' : {m}", p + 1)))?;
        let mut args = args.unwrap_or_default();
        if let Some(val) = conv.val {
            val_conv(cname, val, &mut args).map_err(|e| match e {
                ValErr::Inner(m) => conv_err(format!("invalid args in converter '{cname}' : {m}")),
                // Those end in the period the caller adds to every message.
                ValErr::Whole(m) => conv_err(m.strip_suffix('.').map_or(m.clone(), str::to_string)),
            })?;
        }
        for (n, t) in conv.args.iter().enumerate() {
            if *t == ArgType::Reg {
                if let Some(Arg::Str(re)) = args.get(n) {
                    regexes.push((re.clone(), n + 1, cname));
                }
            }
        }
        i = next;
    }
    // `smp_resolve_args`, once the whole expression has parsed.
    for (re, n, cname) in regexes {
        if let Err(e) = ibex_regex::UserRegex::with_case(&re, false) {
            let kw = if acl { "ACL keyword" } else { "sample fetch keyword" };
            return Err(format!(
                "error in regex '{re}' in arg {n} of conversion keyword '{cname}' for {kw} '{}' : regex '{re}' is invalid ({e})",
                aclkw.unwrap_or(fname)
            ));
        }
    }
    Ok(())
}

