//! T343: the load-time check of a sample expression's arguments against the types every fetch
//! and converter declares, as `HAProxy`'s `sample_parse_expr` does it.
//!
//! Each keyword's argument mask (`ARGn(min, T1, ...)`), `val_args` function and types come from
//! the `HAProxy` source ([`table`], generated by `tools/gen_sample_argspecs.py`). [`check_typed_expr`]
//! walks an expression as `sample_parse_expr` does: the fetch and its arguments
//! ([`make_arg_list`]), the fetch's `val_args`, then each converter: whether its input can be
//! cast from what precedes it (`sample_casts`), its arguments, its `val_args`. A regex argument
//! is compiled last, as `smp_resolve_args` does after the parse. The first failure is returned
//! in `HAProxy`'s words.
//!
//! Before this, an argument of the wrong type (`src,ipmask(255.255.255.O)`) loaded and gave no
//! sample on every request; in an ACL guarding a `deny`, the deny never fired (V&V VV-14).
//!
//! This checks; it does not replace [`crate::Expr::parse`], which also runs when a request is
//! evaluated, where a refusal would silently skip the rule. A keyword `HAProxy` does not have is
//! left to the name checks of the caller.

