//! R2: a `str` sample is bytes, as `HAProxy`'s `smp->data.u.str` is. A header carrying bytes
//! 0x80-0xFF (Latin-1, UTF-8, or neither) goes through the matchers (`-m str/sub/beg/end/
//! reg/len/dom/dir`, with and without `-i`) and the converters (`lower`, `upper`, `field`,
//! `word`, `url_enc`, `json`, ...) byte by byte: `-i` folds ASCII only, `-m len` and
//! `length` count bytes, a regex reads one byte as one character (PCRE2 without UTF), a
//! delimiter is a byte.
//!
//! Every expected value was measured on `HAProxy` 3.5-dev8-885761-29: each row is
//! `http-request set-var(txn.m) bool(1) if { <expr> }` (an ACL row: `1` when it matched) or
//! `http-request set-var(txn.c) <expr>` (a converter row: the value, empty when there is
//! none), read back with `http-response set-header x "%[var(..)]"`, for a request carrying
//! `X: <value>`. The probe is `crates/alcyon-rt/tests/it/bytes_samples_oracle.rs`'s
//! configuration; this table is its output, one row per value and expression.

use alcyon_regex::bytetext::{bytes_to_text, text_to_bytes};
use alcyon_sample::{Expr, Registry, Sample, SampleContext};

/// Calls `f` with the context of `GET /p` carrying the header `X: value`, as the HTTP/1
/// parser leaves it in the HTX.
pub(crate) fn with_request<R>(value: &[u8], f: impl FnOnce(&SampleContext) -> R) -> R {
    let mut wire = b"GET /p HTTP/1.1\r\nHost: h\r\nX: ".to_vec();
    wire.extend_from_slice(value);
    wire.extend_from_slice(b"\r\n\r\n");
    with_request_line(&wire, f)
}

/// Calls `f` with the context of the request head `wire`, as the HTTP/1 parser leaves it.
pub(crate) fn with_request_line<R>(wire: &[u8], f: impl FnOnce(&SampleContext) -> R) -> R {
    let mut parser = alcyon_proto::h1::H1Parser::new(false);
    let mut buf = [0u8; 4096];
    let mut htx = alcyon_proto::htx::HtxSlice::new(&mut buf);
    parser.parse(wire, &mut htx).expect("parse");
    let ctx = SampleContext { phase: &alcyon_sample::PhaseCtx { htx_slice: Some(htx.as_ref()), ..Default::default() }, live: None };
    f(&ctx)
}

/// What `%[...]` prints of a sample: its bytes.
fn rendered(smp: Option<Sample>) -> Vec<u8> {
    match smp {
        None => Vec::new(),
        Some(Sample::Str(s)) => text_to_bytes(&s).into_owned(),
        Some(Sample::Bin(b)) => b,
        Some(Sample::Sint(i)) => i.to_string().into_bytes(),
        Some(Sample::Bool(b)) => if b { b"1".to_vec() } else { b"0".to_vec() },
        Some(Sample::Ipv4(a)) => a.to_string().into_bytes(),
        Some(Sample::Ipv6(a)) => a.to_string().into_bytes(),
        Some(other) => format!("{other:?}").into_bytes(),
    }
}

#[test]
fn a_non_utf8_header_matches_and_converts_as_bytes() {
    let reg = Registry::new();
    let mut wrong = Vec::new();
    for &(value, expr, want) in ORACLE {
        // The configuration's text of the expression, as the lexer gives it (bytetext).
        let text = bytes_to_text(expr);
        let e = Expr::parse(&text).unwrap_or_else(|err| panic!("{}: {err}", expr.escape_ascii()));
        let got = with_request(value, |ctx| {
            if e.matcher.is_some() {
                if e.eval(&reg, ctx) { b"1".to_vec() } else { Vec::new() }
            } else {
                rendered(e.eval_sample(&reg, ctx))
            }
        });
        if got != want {
            wrong.push(format!(
                "X: {} | {} -> got {:?} want {:?}",
                value.escape_ascii(),
                expr.escape_ascii(),
                got.escape_ascii().to_string(),
                want.escape_ascii().to_string()
            ));
        }
    }
    assert!(wrong.is_empty(), "{} of {} rows differ from HAProxy:\n{}", wrong.len(), ORACLE.len(), wrong.join("\n"));
}

